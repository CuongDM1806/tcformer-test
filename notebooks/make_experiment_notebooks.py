"""Build one notebook per experiment from the dataset notebooks.

    python notebooks/make_experiment_notebooks.py

notebooks/<dataset>/all_experiments.ipynb is the template; each experiment gets
notebooks/<dataset>/<run>.ipynb with EXPERIMENTS set to that experiment alone.
Edit the lists below (or a dataset notebook) and run this again.
"""
import copy
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

SSM_DAN = [
    ('ssm_dan', '', 'SSM-DAN (also scores the same weights without IM-TTA: Stage-1 UDA)'),
    ('ssm_dan', 'source_only', 'SSM-DAN ablation: source-only backbone'),
    ('ssm_dan', 'no_ra', 'SSM-DAN ablation: without Riemannian alignment'),
    ('ssm_dan', 'no_da', 'SSM-DAN ablation: without Stage-1 domain adaptation (IM-TTA only)'),
    ('ssm_dan', 'no_ra,no_da', 'SSM-DAN ablation: without RA and Stage-1 domain adaptation (IM-TTA kept)'),
    ('ssm_dan', 'per_session_ra', 'SSM-DAN with the session-specific RA reference'),
]
BASELINES = [
    ('eegconformer', '', 'EEG Conformer (source-only baseline)'),
    ('atcnet', '', 'ATCNet (source-only baseline)'),
    ('tcformer', '', 'TCFormer (source-only baseline)'),
    ('eegencoder', '', 'EEGEncoder (source-only baseline)'),
    ('satransnet', '', 'SATrans-Net (source-only baseline)'),
    ('rmetnet', '', 'RMETNet (domain-adaptation baseline)'),
    ('ttime', '', 'T-TIME (test-time-adaptation baseline)'),
    ('bft', '', 'BFT (test-time-adaptation baseline)'),
]
OPENBMI_EXTRA = [
    ('ssm_dan', 'source_only_head', 'SSM-DAN ablation: source-only training of the full network (paper column)'),
    ('ssm_dan', 'no_car', 'SSM-DAN without common average reference (needs the no-CAR cache)'),
    ('ssm_dan', 'no_car,per_session_ra', 'SSM-DAN without CAR, session-specific RA reference'),
]
EXPERIMENTS = {
    'bcic2a': SSM_DAN + BASELINES,
    'bcic2b': SSM_DAN + BASELINES,
    'zhou2016': SSM_DAN + BASELINES,
    'openbmi': SSM_DAN + OPENBMI_EXTRA + BASELINES,
}


def run_name(method, variant):
    return '-'.join([method] + [v.strip() for v in variant.split(',') if v.strip()])


def source(cell):
    return ''.join(cell['source'])


def set_source(cell, text):
    cell['source'] = text.splitlines(keepends=True)


def build(dataset, method, variant, label, template):
    nb = copy.deepcopy(template)
    cells = nb['cells']
    name = run_name(method, variant)

    intro = source(cells[0]).split('\n', 1)
    set_source(cells[0], f'# {intro[0][2:]}: `{name}`\n\n'
               f'**This notebook runs one experiment: {label}** '
               f'(`--method {method}`' + (f' `--variant {variant}`' if variant else '') + ').\n'
               f'Other experiments: the other notebooks in `notebooks/{dataset}/`; all of them write to the same '
               f'`results/{dataset}/` layout, so steps 7-8 compare every run found there.\n'
               + intro[1])

    settings = next(c for c in cells if c['cell_type'] == 'code' and 'EXPERIMENTS = [' in source(c))
    text = source(settings)
    new = re.sub(r"# \(method, variant\) pairs.*?\nEXPERIMENTS = \[\n.*?\n\]\n",
                 f"EXPERIMENTS = [({method!r}, {variant!r})]   # {label}\n", text, flags=re.S)
    assert new != text, dataset
    set_source(settings, new)
    for cell in cells:
        if cell['cell_type'] == 'code':
            cell['outputs'], cell['execution_count'] = [], None
    return name, nb


def main():
    index = ['# Notebooks, one per experiment\n',
             'Generated by `make_experiment_notebooks.py` from the dataset notebooks '
             '(`<dataset>/all_experiments.ipynb`, which runs several experiments at once). Open one on Kaggle or Colab and run all cells.\n']
    for dataset, experiments in EXPERIMENTS.items():
        template = json.loads((HERE / dataset / 'all_experiments.ipynb').read_text(encoding='utf-8'))
        out = HERE / dataset
        out.mkdir(exist_ok=True)
        index.append(f'\n## {dataset}\n\n| Notebook | Experiment |\n|---|---|')
        for method, variant, label in experiments:
            name, nb = build(dataset, method, variant, label, template)
            (out / f'{name}.ipynb').write_text(json.dumps(nb, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
            index.append(f'| [`{dataset}/{name}.ipynb`]({dataset}/{name}.ipynb) | {label} |')
    (HERE / 'README.md').write_text('\n'.join(index) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
